-- Continuous hydrogen simulation, KST local timestamps. Old trial-run tables are not modified.
BEGIN;
CREATE TABLE REP_DATA_HG_SYS_STATE (
 SYS_ID VARCHAR(12) PRIMARY KEY CHECK (SYS_ID = 'MAIN'),
 STARTED_AT TIMESTAMP NOT NULL, CURSOR_AT TIMESTAMP NOT NULL,
 STORED_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (STORED_BG_NM3 >= 0),
 STORED_HG_KG NUMERIC(18,9) NOT NULL CHECK (STORED_HG_KG >= 0),
 DAILY_HG_KG NUMERIC(18,9) NOT NULL CHECK (DAILY_HG_KG > 0),
 BG_PER_KG NUMERIC(18,9) NOT NULL CHECK (BG_PER_KG > 0),
 ENERGY_PER_KG NUMERIC(18,9) NOT NULL CHECK (ENERGY_PER_KG > 0),
 MAX_PROD_KG_H NUMERIC(18,9) NOT NULL CHECK (MAX_PROD_KG_H > 0),
 REFILL_THRESHOLD NUMERIC(18,9) NOT NULL CHECK (REFILL_THRESHOLD >= 0),
 REFILL_TARGET NUMERIC(18,9) NOT NULL CHECK (REFILL_TARGET <= 20000),
 TANK_CAPA_KG NUMERIC(18,9) NOT NULL CHECK (TANK_CAPA_KG >= 1),
 REG_DATE TIMESTAMP NOT NULL, UPD_DATE TIMESTAMP NOT NULL,
 CHECK (CURSOR_AT >= STARTED_AT), CHECK (REFILL_TARGET - REFILL_THRESHOLD >= 1),
 CONSTRAINT CK_HG_BG_CAPACITY CHECK (STORED_BG_NM3 <= 20000), CHECK (STORED_HG_KG < TANK_CAPA_KG)
);
CREATE TABLE REP_DATA_HG_CONTROL (
 CMD_ID VARCHAR(64) PRIMARY KEY, CMD_TYPE VARCHAR(12) NOT NULL,
 PERCENT_VALUE NUMERIC(18,9), EFFECTIVE_AT TIMESTAMP NOT NULL,
 REQUESTED_AT TIMESTAMP, RECEIVED_AT TIMESTAMP NOT NULL, CMD_SEQ BIGINT NOT NULL UNIQUE,
 CHECK ((CMD_TYPE IN ('NORMAL','STOP') AND PERCENT_VALUE IS NULL)
     OR (CMD_TYPE = 'REDUCE' AND PERCENT_VALUE IS NOT NULL AND PERCENT_VALUE BETWEEN 0 AND 100)
     OR (CMD_TYPE = 'PLUS_DR' AND PERCENT_VALUE IS NOT NULL AND PERCENT_VALUE BETWEEN 0 AND 100))
);
CREATE INDEX IX_HG_CONTROL_EFFECTIVE ON REP_DATA_HG_CONTROL(EFFECTIVE_AT, CMD_SEQ);
CREATE TABLE REP_DATA_HG_HOURLY (
 TM VARCHAR(12) PRIMARY KEY, INTERVAL_START TIMESTAMP NOT NULL, INTERVAL_END TIMESTAMP NOT NULL,
 DURATION_SECONDS INTEGER NOT NULL CHECK (DURATION_SECONDS BETWEEN 1 AND 3600),
 NORMAL_PROD_KG NUMERIC(18,9) NOT NULL CHECK (NORMAL_PROD_KG >= 0),
 DR_PROD_KG NUMERIC(18,9) NOT NULL CHECK (DR_PROD_KG >= 0),
 REDUCED_PROD_KG NUMERIC(18,9) NOT NULL CHECK (REDUCED_PROD_KG >= 0),
 PROD_KG NUMERIC(18,9) NOT NULL CHECK (PROD_KG >= 0),
 ENERGY_KWH NUMERIC(18,9) NOT NULL CHECK (ENERGY_KWH >= 0),
 OPEN_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (OPEN_BG_NM3 >= 0),
 REFILLED_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (REFILLED_BG_NM3 >= 0),
 USED_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (USED_BG_NM3 >= 0),
 STORED_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (STORED_BG_NM3 >= 0),
 OPEN_HG_KG NUMERIC(18,9) NOT NULL CHECK (OPEN_HG_KG >= 0),
 STORED_HG_KG NUMERIC(18,9) NOT NULL CHECK (STORED_HG_KG >= 0),
 SHIPPED_HG_KG NUMERIC(18,9) NOT NULL CHECK (SHIPPED_HG_KG >= 0),
 TANK_EXCHANGES INTEGER NOT NULL CHECK (TANK_EXCHANGES >= 0),
 DR_SECONDS INTEGER NOT NULL CHECK (DR_SECONDS >= 0),
 STOP_SECONDS INTEGER NOT NULL CHECK (STOP_SECONDS >= 0),
 REDUCED_SECONDS INTEGER NOT NULL CHECK (REDUCED_SECONDS >= 0),
 REG_DATE TIMESTAMP NOT NULL,
 CHECK (INTERVAL_END > INTERVAL_START), CHECK (DR_SECONDS + STOP_SECONDS + REDUCED_SECONDS <= DURATION_SECONDS)
);
COMMIT;
