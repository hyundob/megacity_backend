-- PostgreSQL: run once before ddl-auto=validate startup. No changes to existing tables.
BEGIN;
CREATE TABLE REP_DATA_HG_SIM_RUN (
    RUN_ID VARCHAR(36) NOT NULL PRIMARY KEY,
    RUN_NM VARCHAR(80) NOT NULL,
    RUN_MODE VARCHAR(12) NOT NULL,
    RUN_STATUS VARCHAR(12) NOT NULL,
    START_TM VARCHAR(12) NOT NULL,
    NEXT_TM VARCHAR(12) NOT NULL,
    DAILY_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (DAILY_BG_NM3 >= 0),
    DAILY_HG_KG NUMERIC(18,9) NOT NULL CHECK (DAILY_HG_KG >= 0),
    BG_PER_KG NUMERIC(18,9) NOT NULL CHECK (BG_PER_KG >= 0),
    ENERGY_PER_KG NUMERIC(18,9) NOT NULL CHECK (ENERGY_PER_KG >= 0),
    MAX_PROD_KG_H NUMERIC(18,9) NOT NULL CHECK (MAX_PROD_KG_H >= 0),
    HG_CAPA_KG NUMERIC(18,9) NOT NULL CHECK (HG_CAPA_KG >= 0),
    BG_CAPA_NM3 NUMERIC(18,9) NOT NULL CHECK (BG_CAPA_NM3 >= 0),
    INIT_HG_KG NUMERIC(18,9) NOT NULL CHECK (INIT_HG_KG >= 0),
    INIT_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (INIT_BG_NM3 >= 0),
    STORED_HG_KG NUMERIC(18,9) NOT NULL CHECK (STORED_HG_KG >= 0),
    STORED_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (STORED_BG_NM3 >= 0),
    REG_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPD_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (RUN_MODE IN ('SCENARIO', 'REALTIME')),
    CHECK (RUN_STATUS IN ('RUNNING', 'STOPPED')),
    CHECK (STORED_HG_KG <= HG_CAPA_KG AND STORED_BG_NM3 <= BG_CAPA_NM3),
    CHECK (INIT_HG_KG <= HG_CAPA_KG AND INIT_BG_NM3 <= BG_CAPA_NM3),
    CHECK (BG_PER_KG > 0 AND ENERGY_PER_KG > 0),
    CHECK (NEXT_TM >= START_TM)
);

CREATE TABLE REP_DATA_HG_DR_CMD (
    CMD_ID VARCHAR(64) NOT NULL PRIMARY KEY,
    RUN_ID VARCHAR(36) NOT NULL,
    START_TM VARCHAR(12) NOT NULL,
    END_TM VARCHAR(12) NOT NULL,
    TARGET_POWER_KW NUMERIC(18,9) NOT NULL CHECK (TARGET_POWER_KW >= 0),
    REG_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPD_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (RUN_ID) REFERENCES REP_DATA_HG_SIM_RUN(RUN_ID),
    CHECK (END_TM > START_TM),
    CHECK (TARGET_POWER_KW BETWEEN 181.25 AND 522)
);

CREATE TABLE REP_DATA_HG_SIM_H (
    ROW_ID VARCHAR(49) NOT NULL PRIMARY KEY,
    RUN_ID VARCHAR(36) NOT NULL,
    TM VARCHAR(12) NOT NULL,
    NORMAL_PROD_KG NUMERIC(18,9) NOT NULL CHECK (NORMAL_PROD_KG >= 0),
    DR_PROD_KG NUMERIC(18,9) NOT NULL CHECK (DR_PROD_KG >= 0),
    PROD_KG NUMERIC(18,9) NOT NULL CHECK (PROD_KG >= 0),
    ENERGY_KWH NUMERIC(18,9) NOT NULL CHECK (ENERGY_KWH >= 0),
    AVG_POWER_KW NUMERIC(18,9) NOT NULL CHECK (AVG_POWER_KW >= 0),
    OPEN_HG_KG NUMERIC(18,9) NOT NULL CHECK (OPEN_HG_KG >= 0),
    STORED_HG_KG NUMERIC(18,9) NOT NULL CHECK (STORED_HG_KG >= 0),
    OPEN_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (OPEN_BG_NM3 >= 0),
    GEN_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (GEN_BG_NM3 >= 0),
    USED_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (USED_BG_NM3 >= 0),
    STORED_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (STORED_BG_NM3 >= 0),
    OVERFLOW_BG_NM3 NUMERIC(18,9) NOT NULL CHECK (OVERFLOW_BG_NM3 >= 0),
    DR_SECONDS INTEGER NOT NULL CHECK (DR_SECONDS BETWEEN 0 AND 3600),
    HG_CAPACITY_LIMITED BOOLEAN NOT NULL,
    BG_SUPPLY_LIMITED BOOLEAN NOT NULL,
    REG_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPD_DATE TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (RUN_ID) REFERENCES REP_DATA_HG_SIM_RUN(RUN_ID),
    CONSTRAINT UK_HG_SIM_RUN_TM UNIQUE (RUN_ID, TM)
);

CREATE INDEX IX_HG_DR_RUN_TIME ON REP_DATA_HG_DR_CMD (RUN_ID, START_TM, END_TM);
COMMIT;
